// Función para convertir escalas de contenido
export function convertirContenidoAT(
  escala: string,
  bruto: number,
  sexo: 'masculino' | 'femenino'
): number {
  const tablaEscala = TABLA_CONTENIDO_T[escala];
  
  if (!tablaEscala) {
    return Math.min(120, Math.max(30, 50 + bruto));
  }
  
  const valor = tablaEscala[bruto];
  if (valor) {
    return sexo === 'masculino' ? valor.m : valor.f;
  }
  
  const keys = Object.keys(tablaEscala).map(Number).sort((a, b) => a - b);
  const maxKey = keys[keys.length - 1];
  
  if (bruto > maxKey) {
    const last = tablaEscala[maxKey];
    return Math.min(120, (sexo === 'masculino' ? last.m : last.f) + (bruto - maxKey) * 2);
  }
  
  return 50;
}
